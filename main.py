# --- YouTube Auto Post Function ---
def upload_youtube_short(video_path: str, title: str, schedule_time_iso: str):
    secret_path = os.path.join(BASE_DIR, "client_secret.json")
    if not os.path.exists(secret_path):
        print("[Auto-Post] client_secret.json မရှိပါ။")
        return None

    try:
        with open(secret_path, 'r') as f:
            secret_data = json.load(f)

        if "refresh_token" not in secret_data:
            if "installed" in secret_data:
                secret_data = secret_data["installed"]
            elif "web" in secret_data:
                secret_data = secret_data["web"]

        if "refresh_token" not in secret_data:
            return None

        creds = google.oauth2.credentials.Credentials(
            token=None,
            refresh_token=secret_data["refresh_token"],
            token_uri="https://oauth2.googleapis.com/token",
            client_id=secret_data.get("client_id"),
            client_secret=secret_data.get("client_secret")
        )

        youtube = googleapiclient.discovery.build("youtube", "v3", credentials=creds)
        body = {
            "snippet": {
                "title": f"{title} #Shorts #CartoonRecap"[:100],
                "description": f"{title}\n\nAuto 2.5D Cartoon Recap Generated by AI. #Shorts #AnimeRecap",
                "tags": ["Cartoon Recap", "Anime Recap", "Shorts", "Manhwa Recap"],
                "categoryId": "1"
            },
            "status": {
                "privacyStatus": "private",
                "publishAt": schedule_time_iso,
                "selfDeclaredMadeForKids": False
            }
        }

        media = MediaFileUpload(video_path, chunksize=-1, resumable=True, mimetype="video/mp4")
        req = youtube.videos().insert(part="snippet,status", body=body, media_body=media)
        
        response = None
        while response is None:
            status, response = req.next_chunk()
            if status:
                print(f"[Upload Progress] {int(status.progress() * 100)}%")

        return f"https://youtube.com/shorts/{response['id']}"
    except Exception as e:
        print(f"[YouTube Upload Error] {e}")
        return None

# --- Generate Recap Script with Gemini ---
def generate_recap_script(story_topic: str):
    prompt = f"""
Write an exciting, fast-paced 30-45 second Cartoon/Anime recap narration based on this story/topic:
"{story_topic}"

Keep the narration engaging and full of suspense for YouTube Shorts.
Return ONLY valid JSON format:
{{
  "title": "A catchy YouTube Shorts title",
  "narration": "Full narration script for voiceover without speaker tags"
}}
"""
    # Try gemini-3.8-flash first, fallback to standard models
    models_to_try = ["gemini-3.8-flash", "gemini-1.5-flash", "gemini-1.5-pro"]
    last_err = None
    for model_name in models_to_try:
        try:
            res = ai_client.models.generate_content(
                model=model_name,
                contents=prompt,
                config={"response_mime_type": "application/json"}
            )
            return json.loads(res.text)
        except Exception as e:
            last_err = e
            continue
    raise Exception(f"Gemini API Error: {last_err}")

# --- Voiceover Generation (Edge TTS) ---
async def generate_voiceover(text: str, output_audio: str):
    communicate = edge_tts.Communicate(text, "en-US-ChristopherNeural")
    await communicate.save(output_audio)

# --- Get Media Duration ---
def get_audio_duration(audio_path: str) -> float:
    cmd = [
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1", audio_path
    ]
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    return float(result.stdout.strip())

# --- 2.5D Parallax Cartoon Visual Renderer ---
def render_25d_cartoon_video(image_path: str, audio_path: str, duration: float, output_video: str):
    total_frames = int(duration * 30)
    filter_complex = (
        f"[0:v]scale=720:1280:force_original_aspect_ratio=increase,crop=720:1280,boxblur=25:5[bg];"
        f"[0:v]zoompan=z='min(zoom+0.0015,1.25)':d={total_frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=720x1280:fps=30[fg];"
        f"[bg][fg]overlay=0:0[v]"
    )

    cmd = [
        "ffmpeg", "-y", "-loop", "1", "-i", image_path, "-i", audio_path,
        "-filter_complex", filter_complex, "-map", "[v]", "-map", "1:a",
        "-c:v", "libx264", "-tune", "stillimage", "-c:a", "aac", "-b:a", "192k",
        "-pix_fmt", "yuv420p", "-shortest", "-preset", "ultrafast", output_video
    ]
    subprocess.run(cmd, check=True)

# --- Background Automation Pipeline ---
def process_recap_pipeline(task_id: str, story_topic: str, image_file_path: str):
    try:
        db["tasks"][task_id]["status"] = "processing"
        
        # ၁။ Script ရေးသားခြင်း
        db["tasks"][task_id]["message"] = "AI ဖြင့် Cartoon Recap ဇာတ်လမ်း ဇာတ်ညွှန်း ရေးနေပါသည်..."
        script_data = generate_recap_script(story_topic)
        title = script_data.get("title", "Cartoon Recap")
        narration = script_data.get("narration", story_topic)
        db["tasks"][task_id]["title"] = title

        # ၂။ အသံဖိုင် (TTS) ဖန်တီးခြင်း
        db["tasks"][task_id]["message"] = "Voiceover အသံထွက် ဖန်တီးနေပါသည်..."
        audio_path = os.path.join(OUTPUT_DIR, f"{task_id}_voice.mp3")
        asyncio.run(generate_voiceover(narration, audio_path))
        
        duration = get_audio_duration(audio_path)

        # ၃။ 2.5D Parallax Animation Visual ထုတ်လုပ်ခြင်း
        db["tasks"][task_id]["message"] = "2.5D Parallax ရုပ်ကြွ Animation Shorts ဖန်တီးနေပါသည်..."
        final_video_name = f"{task_id}_recap.mp4"
        final_video_path = os.path.join(OUTPUT_DIR, final_video_name)
        
        render_25d_cartoon_video(image_file_path, audio_path, duration, final_video_path)

        # ၄။ YouTube ပေါ်သို့ Schedule Post တင်ခြင်း
        db["tasks"][task_id]["message"] = "YouTube ပေါ်သို့ Shorts အဖြစ် Auto-Post တင်နေပါသည်..."
        sched_time = (datetime.now(timezone.utc) + timedelta(hours=2)).strftime("%Y-%m-%dT%H:%M:%SZ")
        yt_link = upload_youtube_short(final_video_path, title, sched_time)

        # ပြီးဆုံးကြောင်း ပြသခြင်း
        db["tasks"][task_id]["status"] = "completed"
        db["tasks"][task_id]["message"] = "2.5D Cartoon Recap ဖန်တီးပြီး YouTube သို့ အလိုအလျောက် Schedule တင်ပေးလိုက်ပါပြီ!"
        db["tasks"][task_id]["result_url"] = f"/outputs/{final_video_name}"
        db["tasks"][task_id]["youtube_url"] = yt_link

    except Exception as e:
        db["tasks"][task_id]["status"] = "failed"
        db["tasks"][task_id]["message"] = f"Error: {str(e)}"

